import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'

const source = path => readFileSync(`src/components/${path}`, 'utf8')
const bridge = source('three/ScrollLayerBridge.tsx')
assert(bridge.includes("window.addEventListener('wheel', redirectWheel, { passive: true })"), 'Normal portal input cannot block compositor scrolling')
assert(bridge.includes('nested.contains(event.target)'), 'Never apply a native wheel delta twice')
assert(bridge.includes('event.deltaMode === 1') && bridge.includes('event.deltaMode === 2'), 'Line/page wheel units are normalized for HTML chrome forwarding')
assert(bridge.includes("overflowY: locked ? 'hidden' : 'auto'"), 'Focused photos and entry/exit keep exclusive scroll ownership')
const portal = source('experience/EfficientPortalMaterial.tsx')
assert(portal.includes('<PortalActivity.Provider value={visible || phase > 0}>'), 'Photo animation remains active for previews and portal transitions')
const activity = source('experience/portalActivity.ts')
assert(activity.includes('if (!rendering && initialized.current) return'), 'Hidden previews initialize once, then skip photo calculations')
assert(source('experience/album/DriftingWall.tsx').includes('usePortalFrame as useFrame'), 'All photo-wall frame callbacks respect portal visibility')
assert(portal.includes('phase === 2 ? 0'), 'No duplicate preview render inside a full portal')
assert(portal.includes('uniforms.portal.value = surface.uniforms.map.value'), 'Blend reuses the existing scene texture')
assert(!portal.includes('gl.render(scene, camera);\n      gl.setRenderTarget'), 'No second portal scene render during blending')
const tile = source('experience/GridTile.tsx')
assert(tile.includes('useIntersect<THREE.Mesh>(setPortalVisible)'), 'Visibility observer is attached directly to the tile host mesh')
assert(tile.includes('visible={portalVisible}'), 'Offscreen render targets must sleep without unmounting the worlds')
const hero = source('three/Hero.tsx')
assert(hero.includes('shadow-autoUpdate={false}'))
assert(hero.includes('scroll.range(0.4, 0.1) + scroll.range(0.5, 0.1)'), 'Cached shadows track both animated door parts')
assert(hero.includes('light.shadow.needsUpdate = true'), 'Shadows remain live when geometry changes')
console.log('Scroll performance guards passed: native input, portal render reuse/visibility, and motion-invalidated shadows. These are source guards, not FPS benchmarks.')
